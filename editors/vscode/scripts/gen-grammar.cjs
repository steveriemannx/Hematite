// Generate the Hematite TextMate grammar: take VS Code's built-in Rust grammar
// as the base and apply two Hematite-specific patches.
//
// Usage:
//   node scripts/gen-grammar.cjs [path/to/rust.tmLanguage.json]
//
// Without an argument it tries the common VS Code install locations; you can also
// point at the file with the VSCODE_RUST_GRAMMAR environment variable.
"use strict";

const fs = require("fs");
const path = require("path");

const OUT = path.join(__dirname, "..", "syntaxes", "hematite.tmLanguage.json");

function findRustGrammar(argvPath) {
  const candidates = [
    argvPath,
    process.env.VSCODE_RUST_GRAMMAR,
    "/Applications/Visual Studio Code.app/Contents/Resources/app/extensions/rust/syntaxes/rust.tmLanguage.json",
    "/usr/share/code/resources/app/extensions/rust/syntaxes/rust.tmLanguage.json",
    "/usr/lib/code/resources/app/extensions/rust/syntaxes/rust.tmLanguage.json",
  ].filter(Boolean);
  for (const p of candidates) {
    if (fs.existsSync(p)) return p;
  }
  throw new Error(
    "Cannot find rust.tmLanguage.json; pass its path as an argument or set VSCODE_RUST_GRAMMAR."
  );
}

const rustPath = findRustGrammar(process.argv[2]);
const grammar = JSON.parse(fs.readFileSync(rustPath, "utf8"));

// ---------------------------------------------------------------- metadata
grammar.name = "Hematite";
grammar.scopeName = "source.hematite";
grammar.information_for_contributors = [
  "Hematite grammar: based on Microsoft VS Code's built-in Rust grammar (extensions/rust/syntaxes/rust.tmLanguage.json),",
  "which was converted from https://github.com/dustypomerleau/rust-syntax (MIT).",
  "Hematite additions: named return `-> name: Type` and the optional `=` before the function body.",
  "Generated by editors/vscode/scripts/gen-grammar.cjs; do not edit by hand.",
];

// ------------------------------------------------------ Hematite additions
grammar.repository["hematite-signature"] = {
  patterns: [
    {
      comment:
        "Hematite: named return slot `-> name:` (name is any identifier, not a keyword)",
      match: "(->)\\s*((?:r#(?!crate|[Ss]elf|super))?[A-Za-z_][A-Za-z0-9_]*)\\s*(:)",
      captures: {
        1: { name: "keyword.operator.arrow.hematite" },
        2: { name: "variable.parameter.return-name.hematite" },
        3: { name: "punctuation.separator.colon.return-name.hematite" },
      },
    },
    {
      comment: "Hematite: optional `=` before the function body (cpp2 style)",
      match: "(=)(?=\\s*\\{)",
      captures: {
        1: { name: "keyword.operator.assignment.fn-body.hematite" },
      },
    },
  ],
};

// Only touch the "function definition" rule: put the Hematite rules in front of
// the built-in signature patterns.
const fnDef = grammar.repository.functions.patterns.find(
  (p) => p.comment === "function definition"
);
if (!fnDef) {
  throw new Error("Rust grammar layout changed: no `function definition` rule found");
}
fnDef.patterns.unshift({ include: "#hematite-signature" });

// ---------------------------------------------------------------- output
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(grammar, null, 2) + "\n", "utf8");
console.log(`source : ${rustPath}`);
console.log(`output : ${path.relative(process.cwd(), OUT)}`);
